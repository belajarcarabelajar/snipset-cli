import test, { afterEach } from "node:test";
import assert from "node:assert/strict";
import { cpSync, existsSync, mkdtempSync, readdirSync, readFileSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { rm } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const build = join(root, "scripts", "installer", "build.mjs");
const partsDir = join(root, "scripts", "installer", "sh");
const HEADER = "# shellcheck shell=bash disable=SC2034,SC2154";
const NOTICE =
  "# Generated by scripts/installer/build.mjs from scripts/installer/sh/; edit the parts, then run bun scripts/installer/build.mjs.";
const PARTS = [
  "lib.sh",
  "args.sh",
  "platform.sh",
  "fetch.sh",
  "binary.sh",
  "pathenv.sh",
  "shell.sh",
  "db.sh",
  "shims.sh",
  "mcp.sh",
  "modes.sh",
  "main.sh",
];
const USAGE_LINES = [
  "Usage: install.sh [--version VERSION] [--install-dir DIR] [--add-path]",
  "                  [--share-dir DIR] [--db PATH] [--bashrc PATH]",
  "                  [--no-init] [--no-shell] [--no-shims] [--with-mcp]",
  "                  [--help]",
  "  --version VERSION  Release to install (default: latest).",
  "  --install-dir DIR  Binary destination (default: ~/.local/bin).",
  "  --add-path         Append the install dir to PATH in ~/.profile.",
  "  --share-dir DIR    Shell bundle destination (default: ~/.local/share/snipset).",
  "  --db PATH          Database for init/shims (default: the CLI default).",
  "  --bashrc PATH      Shell startup file for integration (default: ~/.bashrc).",
  "  --no-init          Skip creating the standalone database.",
  "  --no-shell         Skip shell integration.",
  "  --no-shims         Skip generating trigger shims.",
  "  --with-mcp         Write ~/.config/opencode/opencode.json if absent.",
  "  --help, -h         Show this help and exit.",
];

const temps = [];
afterEach(async () => {
  while (temps.length) await rm(temps.pop(), { recursive: true, force: true });
});

function temp() {
  const dir = mkdtempSync(join(tmpdir(), "snipset-installer-build-"));
  temps.push(dir);
  return dir;
}

function runBuild(args) {
  const r = spawnSync(process.execPath, [build, ...args], { cwd: root, encoding: "utf8" });
  return { code: r.status, stdout: r.stdout, stderr: r.stderr };
}

function copyRoot() {
  const dir = temp();
  cpSync(partsDir, join(dir, "scripts", "installer", "sh"), { recursive: true });
  cpSync(join(root, "install.sh"), join(dir, "install.sh"));
  return dir;
}

function orderNames(text) {
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"));
}

test("--check --target sh passes on the repo", () => {
  const r = runBuild(["--check", "--target", "sh"]);
  assert.equal(r.code, 0, r.stdout + r.stderr);
});

test("a one-character part edit is drift until the bundle is rebuilt", () => {
  const dir = copyRoot();
  const part = join(dir, "scripts", "installer", "sh", "main.sh");
  writeFileSync(part, readFileSync(part, "utf8").replace("Installed", "installed"));
  const drift = runBuild(["--check", "--target", "sh", "--root", dir]);
  assert.equal(drift.code, 1);
  assert.match(drift.stdout, new RegExp(`drift ${join(dir, "install.sh").replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`));
  const rebuilt = runBuild(["--target", "sh", "--root", dir]);
  assert.equal(rebuilt.code, 0, rebuilt.stderr);
  assert.match(rebuilt.stdout, /^built .*install\.sh$/m);
  assert.equal(runBuild(["--check", "--target", "sh", "--root", dir]).code, 0);
});

test("--check reports a missing bundle", () => {
  const dir = copyRoot();
  unlinkSync(join(dir, "install.sh"));
  const r = runBuild(["--check", "--target", "sh", "--root", dir]);
  assert.equal(r.code, 1);
  assert.match(r.stdout, /^missing .*install\.sh$/m);
  assert.equal(existsSync(join(dir, "install.sh")), false);
});

test("--out writes an executable bundle ending in one newline", () => {
  const out = temp();
  const r = runBuild(["--target", "sh", "--out", out]);
  assert.equal(r.code, 0, r.stderr);
  const file = join(out, "install.sh");
  assert.equal(statSync(file).mode & 0o777, 0o755);
  const text = readFileSync(file, "utf8");
  assert.ok(text.endsWith("\n") && !text.endsWith("\n\n"));
  assert.equal(text, readFileSync(join(root, "install.sh"), "utf8"));
});

test("every part passes bash -n and starts with the shellcheck header", () => {
  for (const name of PARTS) {
    const file = join(partsDir, name);
    const syntax = spawnSync("bash", ["-n", file], { encoding: "utf8" });
    assert.equal(syntax.status, 0, `${name}: ${syntax.stderr}`);
    assert.equal(readFileSync(file, "utf8").split("\n")[0], HEADER, name);
  }
});

test("the bundle starts with the shebang and the notice and drops part headers", () => {
  const lines = readFileSync(join(root, "install.sh"), "utf8").split("\n");
  assert.equal(lines[0], "#!/usr/bin/env bash");
  assert.equal(lines[1], NOTICE);
  assert.equal(lines.filter((line) => line.startsWith("# shellcheck shell=bash")).length, 0);
  assert.equal(statSync(join(root, "install.sh")).mode & 0o777, 0o755);
});

test("ORDER names exactly the part files", () => {
  const order = orderNames(readFileSync(join(partsDir, "ORDER"), "utf8"));
  assert.deepEqual(order, PARTS);
  const files = readdirSync(partsDir).filter((name) => name.endsWith(".sh")).sort();
  assert.deepEqual(files, [...PARTS].sort());
});

test("a part named in ORDER but missing is an error", () => {
  const dir = copyRoot();
  unlinkSync(join(dir, "scripts", "installer", "sh", "modes.sh"));
  const r = runBuild(["--check", "--target", "sh", "--root", dir]);
  assert.equal(r.code, 1);
  assert.match(r.stderr, /modes\.sh/);
});

test("a part file that ORDER does not name is an error", () => {
  const dir = copyRoot();
  writeFileSync(join(dir, "scripts", "installer", "sh", "extra.sh"), `${HEADER}\n`);
  const r = runBuild(["--check", "--target", "sh", "--root", dir]);
  assert.equal(r.code, 1);
  assert.match(r.stderr, /extra\.sh/);
});

test("a missing ORDER for --target ps1 exits 1 and names the path", () => {
  const dir = copyRoot();
  const r = runBuild(["--target", "ps1", "--root", dir]);
  assert.equal(r.code, 1);
  assert.ok(r.stderr.includes(join(dir, "scripts", "installer", "ps1", "ORDER")), r.stderr);
  assert.equal(existsSync(join(dir, "install.ps1")), false);
});

test("an unknown target or flag exits 2", () => {
  assert.equal(runBuild(["--target", "zsh"]).code, 2);
  assert.equal(runBuild(["--bogus"]).code, 2);
  assert.equal(runBuild(["--target"]).code, 2);
});

test("the bundle prints the same usage lines as before", () => {
  const r = spawnSync("bash", [join(root, "install.sh"), "--help"], { encoding: "utf8" });
  assert.equal(r.status, 0, r.stderr);
  const printed = r.stdout.split("\n");
  for (const line of USAGE_LINES) assert.ok(printed.includes(line), `missing usage line: ${line}`);
});
