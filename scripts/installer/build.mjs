#!/usr/bin/env bun
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const USAGE = "usage: bun scripts/installer/build.mjs [--target sh|ps1|all] [--check] [--out DIR] [--root DIR]";
const TARGETS = ["sh", "ps1"];
const PART_EXTENSIONS = [".sh", ".ps1"];
const SH_PART_HEADER = "# shellcheck shell=bash";
const DEFAULT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

class UsageError extends Error {}

function notice(target) {
  return `# Generated by scripts/installer/build.mjs from scripts/installer/${target}/; edit the parts, then run bun scripts/installer/build.mjs.`;
}

export function parseArgs(argv) {
  const opts = { target: "all", check: false, out: undefined, root: DEFAULT_ROOT };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--check") {
      opts.check = true;
    } else if (arg === "--target" || arg === "--out" || arg === "--root") {
      const value = argv[++i];
      if (value === undefined || value === "" || value.startsWith("--")) throw new UsageError(`${arg} needs a value`);
      opts[arg.slice(2)] = value;
    } else {
      throw new UsageError(`unknown argument ${arg}`);
    }
  }
  if (opts.target !== "all" && !TARGETS.includes(opts.target)) throw new UsageError(`unknown target ${opts.target}`);
  opts.root = resolve(opts.root);
  opts.out = resolve(opts.out ?? opts.root);
  return opts;
}

export function readOrder(orderPath) {
  return readFileSync(orderPath, "utf8")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"));
}

export function render(root, target) {
  const dir = join(root, "scripts", "installer", target);
  const orderPath = join(dir, "ORDER");
  if (!existsSync(orderPath)) throw new Error(`missing ${orderPath}`);
  const names = readOrder(orderPath);
  const unlisted = readdirSync(dir)
    .filter((name) => PART_EXTENSIONS.some((ext) => name.endsWith(ext)) && !names.includes(name))
    .sort();
  if (unlisted.length) throw new Error(`${orderPath} does not name ${unlisted.map((name) => join(dir, name)).join(", ")}`);
  const parts = [];
  for (const name of names) {
    const file = join(dir, name);
    if (!existsSync(file)) throw new Error(`${orderPath} names ${name}, but ${file} does not exist`);
    let text = readFileSync(file, "utf8");
    if (target === "sh" && text.startsWith(SH_PART_HEADER)) {
      const newline = text.indexOf("\n");
      text = newline === -1 ? "" : text.slice(newline + 1);
    }
    text = text.replace(/[\r\n]+$/, "");
    // A header-only part (modes.sh today) would otherwise leave a blank line in the bundle.
    if (text) parts.push(text);
  }
  const lines = target === "sh" ? ["#!/usr/bin/env bash", notice(target), ...parts] : [notice(target), ...parts];
  return { file: `install.${target}`, text: `${lines.join("\n")}\n`, mode: target === "sh" ? 0o755 : 0o644 };
}

export function main(argv) {
  let opts;
  try {
    opts = parseArgs(argv);
  } catch (error) {
    if (!(error instanceof UsageError)) throw error;
    console.error(`build.mjs: ${error.message}\n${USAGE}`);
    return 2;
  }
  const targets = opts.target === "all" ? TARGETS : [opts.target];
  let outputs;
  try {
    outputs = targets.map((target) => render(opts.root, target));
  } catch (error) {
    console.error(`build.mjs: ${error.message}`);
    return 1;
  }
  let failed = false;
  for (const output of outputs) {
    const path = join(opts.out, output.file);
    if (opts.check) {
      if (!existsSync(path)) {
        console.log(`missing ${path}`);
        failed = true;
      } else if (readFileSync(path, "utf8") !== output.text) {
        console.log(`drift ${path}`);
        failed = true;
      }
      continue;
    }
    mkdirSync(opts.out, { recursive: true });
    writeFileSync(path, output.text);
    chmodSync(path, output.mode);
    console.log(`built ${path}`);
  }
  return failed ? 1 : 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
